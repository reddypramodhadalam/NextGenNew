"""
api/routes/execution.py

POST /v1/execution/run — the single endpoint the frontend's Execute
button calls, and the same one a check-in trigger calls automatically.
Both hit this route; neither needs to know or care which EXECUTION_MODE
is configured on the backend.

No try/except in this file on purpose. Every failure inside
integrations.run_tests() raises a typed error from core/errors.py,
and api/main.py's central handler is what turns that into a response -
writing it here too would just duplicate that logic per-route, which
is exactly the mistake the central handler exists to prevent.
"""

import logging

from fastapi import APIRouter, Request
from pydantic import BaseModel

from integrations.run_tests import run_tests
from core.middleware import get_correlation_id

logger = logging.getLogger(__name__)
router = APIRouter()


class RunTestsRequest(BaseModel):
    """
    Args:
        app_name (str): which application to run tests for, e.g. "FS".
        test_file_names (list[str]): specific test files selected in
            the UI. Empty list runs every test for that application.
    """
    app_name: str
    test_file_names: list[str] = []


@router.post("/execution/run")
def run(body: RunTestsRequest, request: Request):
    """
    Runs tests for an application.

    Args:
        body (RunTestsRequest): the application and selected test files.
        request (Request): used only to read the current request's
            correlation id, already generated by the middleware.

    Returns:
        dict: the result from integrations.run_tests.run_tests() -
            mode, app_name, overall_status, and per_test_results
            when running locally.
    """
    correlation_id = get_correlation_id()
    logger.info(
        "Execution requested: app=%s files=%s", body.app_name, body.test_file_names,
    )
    return run_tests(body.app_name, body.test_file_names, correlation_id)
