"""
service/iframe_helper.py

Iframe detection and exploration helper for the crawler.

When get_snapshot() encounters iframes, this module provides utilities to:
  1. Detect all iframes on the current page (main document)
  2. Switch to each iframe, capture its elements
  3. Return to main document
  4. Annotate elements with the iframe they came from

Iframes require special handling because Selenium's find_elements() only
searches within the current context (main document or current iframe).
To capture elements inside an iframe, we must call driver.switch_to.frame()
first, then find_elements(), then switch back.

Usage:
    elements = get_snapshot(driver)  # Already handles iframes internally
    # Elements from iframes will have iframe_context: "frame_name"
"""

import logging
from typing import Optional
from selenium.webdriver.common.by import By
from selenium.common.exceptions import WebDriverException

logger = logging.getLogger(__name__)

# JDE's editable grids (e.g. the Sales Order Entry line-item grid) render
# every column's <input> identically — no aria-label, placeholder, name, or
# title. The only place a column's real label ("Item Number", "Unit Price",
# ...) exists is a SEPARATE header <table>, correlated to the data cell only
# through a shared column index: the data cell's ancestor <td colindex="N">
# and the header's <span id="GC<gridid>.N">. Confirmed against a live grid
# DOM sample on 2026-09-09 — data-row inputs carry no name of their own at
# all. Without this lookup, every editable cell in a grid row looks
# identical to the agent (same empty name), so "Enter Item Number" / "Enter
# Unit Price" steps ended up typing into every textbox in the row instead of
# the right one.
#
# The header lookup also returns rowIndex now, in addition to the header
# text. The header text alone is enough to LABEL the cell for a human/LLM
# reading the crawl (resolve_jde_grid_header_name, unchanged below), but
# re-FINDING that exact cell later (from a generated script, on a fresh
# page load) additionally needs to know which data row it was in — see
# resolve_jde_grid_cell_locator. Neither value is ever the grid's own
# jdeGridData<gridid> id: that id is regenerated by JDE on every page load,
# so nothing derived from this lookup is allowed to depend on it — only the
# column header TEXT and the row's POSITION are stable across a refresh.
#
# ROW POSITION — fixed 2026-09-18. JDE renders EACH grid row as its own,
# separate nested <table id="jdeGridData<gridid>.<rownum>"> (confirmed
# against a live multi-row grid DOM sample), not one shared table with
# multiple <tr> rows. The previous approach — count td[colindex="N"]
# siblings within table.closest('table[id^="jdeGridData"]') — always
# resolves to that single-row table (closest() finds the innermost match),
# which only ever contains ONE row, so rowIndex was always computed as 0
# for every row on every screen. This was invisible on a brand-new "Add"
# entry form (exactly one row, so 0 happened to be correct) and only
# breaks once a grid has more than one line item. Fixed by reading the
# `realrow` attribute JDE already puts directly on the data <tr> itself
# (e.g. <tr id="G0_1_R0" realrow="0">), with the old sibling-count kept
# only as a fallback for a grid variant that might lack that attribute.
_JDE_GRID_HEADER_JS = """
var el = arguments[0];
var td = el.closest('td[colindex]');
if (!td) { return null; }
var colindex = td.getAttribute('colindex');
var table = el.closest('table[id^="jdeGridData"]');
if (!table || !table.id) { return null; }
var m = table.id.match(/^jdeGridData(.+)\\.\\d+$/);
if (!m) { return null; }
var gridId = m[1];
var header = document.getElementById('GC' + gridId + '.' + colindex);
if (!header) { return null; }
var headerText = (header.innerText || header.textContent || '');
var rowEl = el.closest('tr[realrow]');
var rowIndex = 0;
if (rowEl && rowEl.getAttribute('realrow') !== null) {
    rowIndex = parseInt(rowEl.getAttribute('realrow'), 10);
    if (isNaN(rowIndex)) { rowIndex = 0; }
} else {
    var rows = Array.from(table.querySelectorAll('td[colindex="' + colindex + '"]'));
    rowIndex = rows.indexOf(td);
}
return {headerText: headerText, rowIndex: rowIndex};
"""


def _resolve_jde_grid_cell(driver, el) -> Optional[dict]:
    """
    Shared lookup behind resolve_jde_grid_header_name and
    resolve_jde_grid_cell_locator — runs the DOM script once and returns
    both pieces of information it produces.

    Returns {"header": "Item Number", "row_index": 0}, or None if el is
    not inside a recognizable JDE grid data cell.
    """
    try:
        raw = driver.execute_script(_JDE_GRID_HEADER_JS, el)
    except WebDriverException as e:
        logger.debug("_resolve_jde_grid_cell: script failed: %s", e)
        return None
    if not raw or not raw.get("headerText"):
        return None
    return {
        "header": " ".join(raw["headerText"].split()),
        "row_index": raw.get("rowIndex", 0),
    }


def resolve_jde_grid_header_name(driver, el) -> Optional[str]:
    """
    Look up the real column label for a JDE editable-grid cell, e.g. an
    <input> inside the Sales Order Entry line-item grid.

    Returns the header text (e.g. "Item Number") with embedded newlines
    (from a <br> in the header, e.g. "Item\\nNumber") normalized to a
    single space, or None if el is not inside a recognizable JDE grid
    data cell (in which case the caller's existing name-fallback chain
    is unaffected).
    """
    result = _resolve_jde_grid_cell(driver, el)
    return result["header"] if result else None


def resolve_jde_grid_cell_locator(driver, el) -> Optional[dict]:
    """
    Build a reusable, refresh-safe "recipe" for re-finding this exact grid
    cell later, e.g. from a generated Selenium script on a fresh page load.

    Deliberately excludes the grid's own DOM id (jdeGridData<gridid>) —
    JDE regenerates that id every page load, so a recipe built from it
    would break on the very next run. Only the column header TEXT and the
    cell's ROW POSITION are included, both of which are stable across a
    refresh; whatever re-derives the cell from this recipe must re-look-up
    the current gridId/colindex live, the same way this function just did.

    Returns {"strategy": "jde_grid_header", "column": "Item Number",
    "row_index": 0}, or None if el is not a recognizable JDE grid cell.
    """
    result = _resolve_jde_grid_cell(driver, el)
    if not result:
        return None
    return {
        "strategy": "jde_grid_header",
        "column": result["header"],
        "row_index": result["row_index"],
    }


def detect_iframes(driver) -> list[tuple[str, str, object]]:
    """
    Find all iframes in the main document.

    This function operates in the main document context. It finds all <iframe>
    and <frame> elements visible on the page and returns metadata about each.

    Args:
        driver: A live Selenium WebDriver instance (must be in main document).

    Returns:
        List of tuples: (frame_name_or_id, iframe_title, iframe_element).
        Each tuple represents one iframe found.
        Empty list if no iframes detected or if an error occurs.

    Note:
        Does NOT switch context. Caller must manage driver.switch_to as needed.
    """
    try:
        # Find both <iframe> and <frame> elements (legacy HTML)
        iframes = driver.find_elements(By.CSS_SELECTOR, "iframe, frame")
        logger.debug("detect_iframes: found %d iframe(s) on page", len(iframes))

        result = []
        for iframe_el in iframes:
            try:
                # Try to get a meaningful identifier for the iframe
                frame_id = (
                    iframe_el.get_attribute("id")
                    or iframe_el.get_attribute("name")
                    or f"frame_{len(result)}"
                )
                frame_title = iframe_el.get_attribute("title") or frame_id
                result.append((frame_id, frame_title, iframe_el))
            except Exception as e:
                logger.warning("detect_iframes: could not read iframe metadata: %s", e)
                continue

        return result

    except WebDriverException as e:
        logger.warning("detect_iframes: could not search for iframes: %s", e)
        return []


def snapshot_iframe_contents(
    driver,
    iframe_element: object,
    frame_name: str,
    selector: str,
    poll_timeout: float = 0.5,
    min_elements: int = 1,
) -> list[dict]:
    """
    Switch to an iframe, read its interactive elements, and return to main.

    This function encapsulates the full iframe exploration cycle:
    1. Switch to the iframe context
    2. Poll briefly for at least min_elements matching element(s) to appear
       (the iframe's content may still be loading asynchronously at the
       moment we switch in)
    3. Find all interactive elements matching the given selector
    4. Annotate each element with iframe_context = frame_name
    5. Switch back to main document
    6. Return the annotated elements

    Args:
        driver: A live Selenium WebDriver instance (should be in main context).
        iframe_element: The <iframe> WebElement returned by detect_iframes.
        frame_name: Identifier for the iframe (id, name, or synthetic name).
        selector: CSS selector to find interactive elements (e.g., INTERACTIVE_SELECTOR).
        poll_timeout: Max seconds to wait for the iframe's content to render
            before accepting whatever is currently present (default 2.0).
            Frames that never gain matching elements (e.g. genuinely empty
            hidden/utility iframes) simply wait out this timeout once and
            return empty, same as before.
        min_elements: Minimum element count to wait for before accepting the
            result as final (default 1 — unchanged prior behavior). Callers
            that know a click just navigated this specific frame can pass a
            higher value (with a longer poll_timeout) to avoid capturing the
            frame mid-transition — see explore_iframes' just_clicked handling.

    Returns:
        List of element dicts with "iframe_context" field added.
        Example: {"ref": "ifr-el-0", "role": "button", "name": "Submit", "iframe_context": "frame_1"}
        Empty list if iframe is unreachable or has no matching elements.
    """
    from selenium.webdriver.support.wait import WebDriverWait
    from selenium.common.exceptions import TimeoutException

    elements = []
    try:
        # Switch into the iframe
        driver.switch_to.frame(iframe_element)
        logger.debug("snapshot_iframe_contents: switched to iframe '%s'", frame_name)

        # The iframe's content may still be loading asynchronously right
        # after switching in. Give it a short, bounded chance to render
        # before treating an empty (or too-small, see min_elements) result
        # as final.
        try:
            WebDriverWait(driver, poll_timeout).until(
                lambda d: len(d.find_elements(By.CSS_SELECTOR, selector)) >= min_elements
            )
        except TimeoutException:
            pass  # Genuinely empty/small (or slower than poll_timeout) — proceed as before.

        # Find interactive elements within the iframe
        iframe_elements = driver.find_elements(By.CSS_SELECTOR, selector)
        logger.debug(
            "snapshot_iframe_contents: found %d elements in iframe '%s'",
            len(iframe_elements),
            frame_name,
        )

        # Process each element: read its properties and annotate
        for i, el in enumerate(iframe_elements):
            try:
                if not el.is_displayed():
                    continue
                if el.get_attribute("aria-hidden") == "true":
                    continue

                # Use a different ref namespace to distinguish iframe elements from main doc
                ref = f"ifr-{frame_name}-el-{i}"
                role = el.get_attribute("role") or el.tag_name

                # locator records WHICH real attribute actually produced the
                # name below (or the JDE grid recipe, for a cell that has no
                # real attribute at all) — a generated script transcribes a
                # selector straight from this instead of re-guessing one from
                # the flattened name text. See service.trace_compiler.
                # Preserves the exact original name-precedence order:
                # aria-label, placeholder, visible text, title.
                name = ""
                locator: Optional[dict] = None
                for attr, getter in (
                    ("aria-label", lambda: el.get_attribute("aria-label")),
                    ("placeholder", lambda: el.get_attribute("placeholder")),
                    ("text", lambda: el.text),
                    ("title", lambda: el.get_attribute("title")),
                ):
                    value = (getter() or "").strip()
                    if value:
                        name = value
                        locator = {"strategy": "attribute", "attr": attr, "value": value}
                        break

                if not name and el.tag_name.lower() in ("input", "textarea", "select"):
                    # See resolve_jde_grid_cell_locator — editable grid cells
                    # (e.g. Item Number / Unit Price in the Sales Order Entry
                    # line-item grid) carry no name of their own. locator here
                    # is a recipe (column header + row position), never the
                    # grid's own DOM id — JDE regenerates that id every page
                    # load, so nothing recorded here may depend on it.
                    grid_locator = resolve_jde_grid_cell_locator(driver, el)
                    if grid_locator:
                        name = grid_locator["column"]
                        locator = grid_locator

                # Same decorative-placeholder noise filtered in
                # core.tools.get_snapshot — see comment there. Applies here
                # too since iframe content can contain the same kind of
                # leftover no-iframe-support fallback text.
                if "iframe support is required" in name.lower():
                    continue

                element_dict = {
                    "ref": ref,
                    "role": role,
                    "name": name,
                    "iframe_context": frame_name,  # Key annotation
                    "locator": locator,
                }
                elements.append(element_dict)

            except Exception as e:
                logger.debug("snapshot_iframe_contents: skipped element in iframe: %s", e)
                continue

        logger.info(
            "snapshot_iframe_contents: captured %d elements from iframe '%s'",
            len(elements),
            frame_name,
        )

    except WebDriverException as e:
        logger.warning(
            "snapshot_iframe_contents: could not access iframe '%s': %s", frame_name, e
        )

    finally:
        # Always return to main document
        try:
            driver.switch_to.default_content()
            logger.debug("snapshot_iframe_contents: returned to main document")
        except WebDriverException as e:
            logger.error("snapshot_iframe_contents: failed to return to main document: %s", e)

    return elements


# Per-URL cache of consecutive "empty" results for each iframe. A frame
# that reliably comes back empty (e.g. LOGOUT_IFRAME, RunAppHiddenIframe —
# hidden/utility iframes JDE always includes) does not need a full
# switch-in + poll + switch-out cycle on every single snapshot. Cleared
# implicitly whenever the URL changes (a new dict is created per URL).
# Because some apps (e.g. JDE) can replace a frame's content under the
# SAME url, a skipped frame is still re-probed eventually rather than being
# skipped forever — but the interval backs off exponentially (3, 6, 12, ...
# capped at MAX_RECHECK_INTERVAL) instead of a fixed "every 3rd call"
# forever. A frame that has genuinely been empty every time for the whole
# session (JDE's structural shell iframes almost always are) quickly stops
# costing a full rescan on a tight fixed schedule, while still eventually
# being re-checked in case content really does appear later.
INITIAL_RECHECK_INTERVAL = 3
MAX_RECHECK_INTERVAL = 30
# Backward-compat alias — some callers/tests may still reference the old name.
RECHECK_INTERVAL = INITIAL_RECHECK_INTERVAL
_empty_streak_by_url: dict[str, dict[str, dict]] = {}

# The one iframe JDE actually renders real application screens into (menu,
# forms, grids). Confirmed via a live debugging session on 2026-09-11: right
# after clicking a final menu leaf (e.g. "Standard Order SO"), this frame
# briefly still shows its prior near-empty placeholder state (as few as 1
# element) while the real form is still rendering — the default 0.5s poll is
# nowhere near enough for that transition. Every other iframe on the page is
# either a fixed structural shell frame or a utility/hidden frame that does
# not need this extra patience, so the extra wait below is scoped to just
# this one frame_id rather than applied broadly.
MAIN_CONTENT_IFRAME_ID = "e1menuAppIframe"
# Bounded extra wait applied only to MAIN_CONTENT_IFRAME_ID, only on the
# snapshot taken immediately after a click (see just_clicked below).
_POST_CLICK_POLL_TIMEOUT = 3.0
_POST_CLICK_MIN_ELEMENTS = 2


def explore_iframes(driver, iframes: list, selector: str, just_clicked: bool = False) -> list[dict]:
    """
    Snapshot a pre-detected list of iframes (as returned by detect_iframes),
    skipping frames that have reliably come back empty on recent calls for
    the current URL.

    Use this when the caller already has the iframe list, to avoid querying
    the DOM for iframes a second time in the same snapshot. Use
    explore_all_iframes when it doesn't.

    Args:
        driver: A live Selenium WebDriver instance (must be in main document).
        iframes: List of (frame_id, frame_title, iframe_element) as returned
            by detect_iframes.
        selector: CSS selector for interactive elements.
        just_clicked: When True, MAIN_CONTENT_IFRAME_ID is given extra time
            (and a minimum-element threshold) to finish rendering before its
            snapshot is accepted, instead of the default quick poll. Every
            other iframe is unaffected. Defaults to False, which reproduces
            the exact prior behavior for all callers that don't pass it.

    Returns:
        List of element dicts from all iframes, each annotated with iframe_context.
    """
    all_elements: list[dict] = []
    if not iframes:
        return all_elements

    try:
        url = driver.current_url
    except Exception:
        url = ""
    streaks = _empty_streak_by_url.setdefault(url, {}) if url else {}

    skipped = 0
    for frame_id, frame_title, iframe_el in iframes:
        state = streaks.get(frame_id)
        if state and 0 < state["streak"] < state["interval"]:
            logger.debug(
                "explore_iframes: skipping known-empty frame '%s' (streak=%d/%d)",
                frame_id, state["streak"], state["interval"],
            )
            state["streak"] += 1
            skipped += 1
            continue

        if just_clicked and frame_id == MAIN_CONTENT_IFRAME_ID:
            elements = snapshot_iframe_contents(
                driver, iframe_el, frame_id, selector,
                poll_timeout=_POST_CLICK_POLL_TIMEOUT,
                min_elements=_POST_CLICK_MIN_ELEMENTS,
            )
        else:
            elements = snapshot_iframe_contents(driver, iframe_el, frame_id, selector)
        all_elements.extend(elements)
        if elements:
            # Content found — reset fully, next empty streak (if any) starts
            # the backoff over from INITIAL_RECHECK_INTERVAL.
            streaks[frame_id] = {"streak": 0, "interval": INITIAL_RECHECK_INTERVAL}
        else:
            # Empty again — double how long we'll wait before the next full
            # recheck (capped), instead of rechecking on the same fixed
            # schedule forever.
            prev_interval = state["interval"] if state else INITIAL_RECHECK_INTERVAL
            next_interval = (
                min(prev_interval * 2, MAX_RECHECK_INTERVAL) if state else INITIAL_RECHECK_INTERVAL
            )
            streaks[frame_id] = {"streak": 1, "interval": next_interval}

    logger.info(
        "explore_iframes: captured %d total elements from %d iframe(s) (%d skipped as known-empty)",
        len(all_elements), len(iframes), skipped,
    )
    return all_elements


def explore_all_iframes(driver, selector: str) -> list[dict]:
    """
    Convenience function: detect all iframes, snapshot each, return all elements.

    This is a higher-level API that chains detect_iframes + explore_iframes
    for cases where the caller does not already have the iframe list (see
    explore_iframes for the empty-frame skip/recheck behaviour).

    Args:
        driver: A live Selenium WebDriver instance (must be in main document).
        selector: CSS selector for interactive elements.

    Returns:
        List of element dicts from all iframes, each annotated with iframe_context.
        Empty list if no iframes found or if all fail.
    """
    try:
        iframes = detect_iframes(driver)
        if not iframes:
            logger.debug("explore_all_iframes: no iframes found on page")
            return []
        return explore_iframes(driver, iframes, selector)

    except Exception as e:
        logger.error("explore_all_iframes: unexpected error: %s", e)
        return []


# Backward compatibility: a simple cache so the crawl agent and tools
# can annotate elements with their iframe context when needed later.
_IFRAME_ELEMENT_CACHE: dict[str, dict] = {}


def store_iframe_element(ref: str, context: dict) -> None:
    """Store metadata about an iframe element for later lookup.

    Args:
        ref: Element reference (e.g., "ifr-frame_1-el-5").
        context: Dict with iframe metadata (frame_name, frame_title, etc.).
    """
    _IFRAME_ELEMENT_CACHE[ref] = context
    logger.debug("store_iframe_element: stored context for ref=%s", ref)


def get_iframe_context(ref: str) -> Optional[dict]:
    """Retrieve stored iframe context for an element.

    Args:
        ref: Element reference.

    Returns:
        Dict with iframe metadata, or None if not found.
    """
    return _IFRAME_ELEMENT_CACHE.get(ref)
